export const generateMockIndicatorValues = (): IndicatorValue[] => {
  const values: IndicatorValue[] = [];
  const indicators = [...mockHealthIndicators, ...mockEducationIndicators];
  const entities = [...mockRegions, ...mockDepartments.slice(0, 4)];
  const years = [2022, 2023, 2024];
  const statuses = ['validated', 'validated', 'validated', 'pending', 'draft'];

  indicators.forEach((indicator) => {
    entities.forEach((entity) => {
      years.forEach((year) => {
        const baseValue = indicator.targetValue || 50;
        const variation = (Math.random() - 0.5) * 30;
        const value = Math.max(0, baseValue + variation);
        const previousValue = value + (Math.random() - 0.5) * 10;
        const variation_pct = ((value - previousValue) / previousValue) * 100;

        values.push({
          id: `${indicator.id}_${entity.id}_${year}`,
          indicatorId: indicator.id,
          indicatorCode: indicator.code,
          indicatorName: indicator.name,
          geographicId: entity.id,
          geographicLevel: entity.level,
          geographicName: entity.name,
          year,
          value: Math.round(value * 100) / 100,
          valueFormatted: indicator.type === 'percentage' 
            ? `${Math.round(value * 10) / 10}%`
            : `${Math.round(value * 10) / 10}`,
          previousValue: Math.round(previousValue * 100) / 100,
          variation: Math.round(variation_pct * 100) / 100,
          targetValue: indicator.targetValue,
          achievementRate: indicator.targetValue 
            ? Math.round((value / indicator.targetValue) * 1000) / 10
            : undefined,
          status: statuses[Math.floor(Math.random() * statuses.length)] as any,
          source: 'Source nationale',
          createdAt: `${year}-12-31T00:00:00Z`,
          updatedAt: `${year}-12-31T00:00:00Z`,
        });
      });
    });
  });

  return values;
};

